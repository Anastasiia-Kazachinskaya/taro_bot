private fun orientationOf(reversed: Boolean) = if (reversed) "перевёрнутая" else "прямая"

/** Renders each card's position/name/arcana/suit/orientation/meaning as a text block, ported from `_format_cards_text`. */
fun formatCardsText(cards: List<SpreadCard>): String =
    cards.joinToString("") { spreadCard ->
        val card = spreadCard.card
        """

Карта ${spreadCard.positionIndex}
Позиция: ${spreadCard.positionLabel}
Название: ${card.name}
Аркан: ${card.arcana}
Масть: ${card.suit.ifBlank { "нет" }}
Положение: ${orientationOf(card.reversed)}
Значение: ${card.meaning}
"""
    }

/**
 * The response hit `max_tokens`: trims the cut-off tail at the last paragraph or
 * sentence boundary (if that boundary is past 60% of the text) and notes the
 * truncation, ported from `trim_truncated`.
 */
fun trimTruncated(text: String): String {
    val trimmed = text.trimEnd()
    val paragraphEnd = trimmed.lastIndexOf("\n\n")
    val cut = if (paragraphEnd > trimmed.length * 0.6) {
        trimmed.substring(0, paragraphEnd)
    } else {
        val sentenceEnd = maxOf(
            trimmed.lastIndexOf(". "),
            trimmed.lastIndexOf("! "),
            trimmed.lastIndexOf("? "),
            trimmed.lastIndexOf(".\n"),
        )
        if (sentenceEnd > trimmed.length * 0.6) trimmed.substring(0, sentenceEnd + 1) else trimmed
    }
    return cut.trimEnd() + "\n\n(Интерпретация получилась длиннее лимита и была сокращена.)"
}

/** `max_tokens` formula ported from `interpret_tarot`: a single card gets a fixed budget, more cards scale up to a cap. */
fun maxTokensForSpread(cardCount: Int): Int = if (cardCount <= 1) 700 else minOf(2800, 500 + cardCount * 150)
