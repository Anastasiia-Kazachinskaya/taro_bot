def interpret_tarot(
    question: str,
    spread_name: str,
    spread: list[dict]
) -> str:

    cards_text = []

    for index, item in enumerate(spread, start=1):
        card = item["card"]
        position = item["position"]

        orientation = (
            "прямая"
            if not card["reversed"]
            else "перевёрнутая"
        )

        cards_text.append(
            f"""
Карта {index}
Позиция: {position}
Название: {card["name"]}
Аркан: {card["arcana"]}
Масть: {card["suit"] or "нет"}
Положение: {orientation}
Значение: {card["meaning"]}
"""
        )

    prompt = f"""
Вопрос пользователя:
{question}

Название расклада:
{spread_name}

Карты расклада:
{"".join(cards_text)}

Прочитай этот расклад именно как ответ
на вопрос пользователя.

Не пересказывай переданное значение карты.
Используй его только как основу для интерпретации.

Свяжи карту с конкретным смыслом вопроса.

Не придумывай обстоятельства жизни пользователя,
которых нет в вопросе.

Если вопрос общий — дай общее, но содержательное чтение.
Если вопрос касается решения — анализируй решение.
Если вопрос касается отношений — анализируй динамику отношений.

Для одной карты:
дай ровно 3 содержательных абзаца,
без заголовков и без отдельного заключения.

Для нескольких карт:
интерпретируй позиции и свяжи карты
в единый сюжет.

Не добавляй ничего кроме готовой интерпретации.
"""


    response = client.chat.completions.create(
        model="ai-sage/GigaChat3.5-432B-A28B",
        max_tokens=1000,
        temperature=0.7,
        presence_penalty=0,
        top_p=1,
        messages=[
            {
                "role": "system",
                "content": SYSTEM_PROMPT
            },
            {
                "role": "user",
                "content": prompt
            }
        ]
    )

    result = response.choices[0].message.content

    if not result:
        raise ValueError(
            "Cloud.ru вернул пустой ответ"
        )

    return result